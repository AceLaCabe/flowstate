// lib/calendar/date-utils.ts

export type CalendarDatePart = {
  year: number;
  month: number;
  day: number;
};

export type EventTiming = "start" | "ongoing" | "end" | "single";

type TimedEvent = {
  start_time: string;
  end_time: string;
};

/**
 * Returns a YYYY-MM-DD key for a timestamp in the
 * user's selected IANA time zone.
 */
export function getZonedDateKey(
  timestamp: string | Date,
  timeZone: string
): string {
  const date =
    timestamp instanceof Date
      ? timestamp
      : new Date(timestamp);

  const parts = new Intl.DateTimeFormat("en-US", {
    timeZone,
    year: "numeric",
    month: "2-digit",
    day: "2-digit",
  }).formatToParts(date);

  const getPart = (type: string) =>
    parts.find((part) => part.type === type)?.value ?? "";

  return [
    getPart("year"),
    getPart("month"),
    getPart("day"),
  ].join("-");
}

/**
 * Converts a calendar date into YYYY-MM-DD without
 * interpreting it as a UTC timestamp.
 *
 * Use this for dates generated by the browser calendar.
 */
export function getCalendarDateKey(date: Date): string {
  return [
    date.getFullYear(),
    String(date.getMonth() + 1).padStart(2, "0"),
    String(date.getDate()).padStart(2, "0"),
  ].join("-");
}

/**
 * Returns a Date representing the first day of the
 * week (Sunday) for calendar navigation.
 */
export function startOfCalendarWeek(date: Date): Date {
  const result = new Date(date);

  result.setDate(result.getDate() - result.getDay());
  result.setHours(0, 0, 0, 0);

  return result;
}

/**
 * Formats an actual event timestamp in the viewer's
 * selected time zone.
 */
export function formatZonedTime(
  timestamp: string,
  timeZone: string
): string {
  return new Intl.DateTimeFormat("en-US", {
    hour: "numeric",
    minute: "2-digit",
    timeZone,
  }).format(new Date(timestamp));
}

/**
 * Formats an event timestamp as a date and time.
 */
export function formatZonedDateTime(
  timestamp: string,
  timeZone: string
): string {
  return new Intl.DateTimeFormat("en-US", {
    month: "short",
    day: "numeric",
    year: "numeric",
    hour: "numeric",
    minute: "2-digit",
    timeZone,
  }).format(new Date(timestamp));
}

/**
 * Determines whether an event overlaps a date
 * in the viewer's selected time zone.
 */
export function eventOccursOnDate(
  event: TimedEvent,
  date: Date,
  timeZone: string
): boolean {
  const dateKey = getCalendarDateKey(date);

  const startKey = getZonedDateKey(
    event.start_time,
    timeZone
  );

  const endKey = getZonedDateKey(
    event.end_time,
    timeZone
  );

  return startKey <= dateKey && endKey >= dateKey;
}

/**
 * Determines how a timed event should be labeled
 * on a particular calendar date.
 */
export function getEventTiming(
  event: TimedEvent,
  date: Date,
  timeZone: string
): EventTiming {
  const dateKey = getCalendarDateKey(date);

  const startKey = getZonedDateKey(
    event.start_time,
    timeZone
  );

  const endKey = getZonedDateKey(
    event.end_time,
    timeZone
  );

  if (startKey === endKey) {
    return "single";
  }

  if (dateKey === startKey) {
    return "start";
  }

  if (dateKey === endKey) {
    return "end";
  }

  return "ongoing";
}

/**
 * Returns a short display label for an event
 * appearing on a specific calendar day.
 */
export function getEventDayLabel(
  event: TimedEvent,
  date: Date,
  timeZone: string
): string {
  const timing = getEventTiming(event, date, timeZone);

  switch (timing) {
    case "start":
      return `Starts ${formatZonedTime(
        event.start_time,
        timeZone
      )}`;

    case "end":
      return `Ends ${formatZonedTime(
        event.end_time,
        timeZone
      )}`;

    case "ongoing":
      return "Ongoing";

    default:
      return formatZonedTime(
        event.start_time,
        timeZone
      );
  }
}

/**
 * Checks whether an event overlaps a calendar date range.
 *
 * startKey and endKey must use YYYY-MM-DD format.
 * Both boundaries are inclusive.
 */
export function eventOverlapsDateRange(
  event: TimedEvent,
  startKey: string,
  endKey: string,
  timeZone: string
): boolean {
  const eventStartKey = getZonedDateKey(
    event.start_time,
    timeZone
  );

  const eventEndKey = getZonedDateKey(
    event.end_time,
    timeZone
  );

  return (
    eventStartKey <= endKey &&
    eventEndKey >= startKey
  );
}